-- Shared helpdesk metadata (additive migration; Forumotion remains the ticket/conversation source)
-- Requires the existing public.translation_admins table and Supabase Auth.
-- Does not import, move, update, or delete Forumotion tickets or existing application data.

begin;

create table if not exists public.helpdesk_ticket_metadata (
  ticket_key text primary key,
  forumotion_topic_id text not null,
  forumotion_forum_id integer not null,
  ticket_number text,
  subject text,
  category text,
  department text,
  status text not null default 'pending'
    check (status in ('pending','progress','done','refused')),
  priority text not null default 'normal'
    check (priority in ('low','normal','high','urgent')),
  assignee_forumotion_user_id bigint,
  assignee_name text,
  internal_note text not null default '',
  created_by_forumotion_user_id bigint,
  created_by_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  updated_by uuid,
  constraint helpdesk_ticket_metadata_key_format
    check (ticket_key = forumotion_forum_id::text || ':' || forumotion_topic_id)
);

create index if not exists helpdesk_ticket_metadata_status_idx
  on public.helpdesk_ticket_metadata (status);
create index if not exists helpdesk_ticket_metadata_assignee_idx
  on public.helpdesk_ticket_metadata (assignee_forumotion_user_id);
create index if not exists helpdesk_ticket_metadata_updated_idx
  on public.helpdesk_ticket_metadata (updated_at desc);

alter table public.helpdesk_ticket_metadata enable row level security;

drop policy if exists "Helpdesk admins can read ticket metadata" on public.helpdesk_ticket_metadata;
create policy "Helpdesk admins can read ticket metadata"
  on public.helpdesk_ticket_metadata for select to authenticated
  using (exists (
    select 1 from public.translation_admins a where a.user_id = auth.uid()
  ));

drop policy if exists "Helpdesk admins can insert ticket metadata" on public.helpdesk_ticket_metadata;
create policy "Helpdesk admins can insert ticket metadata"
  on public.helpdesk_ticket_metadata for insert to authenticated
  with check (exists (
    select 1 from public.translation_admins a where a.user_id = auth.uid()
  ));

drop policy if exists "Helpdesk admins can update ticket metadata" on public.helpdesk_ticket_metadata;
create policy "Helpdesk admins can update ticket metadata"
  on public.helpdesk_ticket_metadata for update to authenticated
  using (exists (
    select 1 from public.translation_admins a where a.user_id = auth.uid()
  ))
  with check (exists (
    select 1 from public.translation_admins a where a.user_id = auth.uid()
  ));

-- Append-only audit trail for moderation changes.
create table if not exists public.helpdesk_ticket_events (
  id bigint generated by default as identity primary key,
  ticket_key text not null
    references public.helpdesk_ticket_metadata(ticket_key) on delete restrict,
  event_type text not null
    check (event_type in ('created','status_changed','priority_changed','assigned','note_added','metadata_updated')),
  event_data jsonb not null default '{}'::jsonb,
  actor_user_id uuid not null default auth.uid(),
  created_at timestamptz not null default now()
);

create index if not exists helpdesk_ticket_events_ticket_idx
  on public.helpdesk_ticket_events (ticket_key, created_at desc);

alter table public.helpdesk_ticket_events enable row level security;

drop policy if exists "Helpdesk admins can read ticket events" on public.helpdesk_ticket_events;
create policy "Helpdesk admins can read ticket events"
  on public.helpdesk_ticket_events for select to authenticated
  using (exists (
    select 1 from public.translation_admins a where a.user_id = auth.uid()
  ));

drop policy if exists "Helpdesk admins can append ticket events" on public.helpdesk_ticket_events;
create policy "Helpdesk admins can append ticket events"
  on public.helpdesk_ticket_events for insert to authenticated
  with check (
    actor_user_id = auth.uid()
    and exists (
      select 1 from public.translation_admins a where a.user_id = auth.uid()
    )
  );

grant select, insert, update on public.helpdesk_ticket_metadata to authenticated;
grant select, insert on public.helpdesk_ticket_events to authenticated;

commit;
